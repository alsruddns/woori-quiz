export function generalKoreanCopy(question: QuizQuestion): { question: string; options: string[]; explanation: string } | undefined {
  if (!question.id.startsWith("general-x-")) return undefined;
  const index = Number(question.id.slice("general-x-".length)) - 1;
  const row = rows[index];
  if (!row) return undefined;
  return { question: row[0], options: question.options.map((option) => answers[option] ?? option), explanation: row[1] };
}
